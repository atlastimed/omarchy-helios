"""Key exchange and ciphers used by the Zepp OS handshake.

The strap runs ECDH on NIST B-163 (sect163r2) and serialises points the way
tiny-ECDH-c does: each coordinate as six little-endian 32-bit words, 24 bytes,
x then y. Field elements here are plain ints, bit i holding the coefficient of
z^i, so int.to_bytes(24, "little") produces that layout directly.

AES-128 is written out here too, rather than taken from a library. Helios
uses it for a few short control messages a minute (history travels
unencrypted on its own characteristic) and once for the Zepp sign-in form, so
speed is no concern, and it would be the only reason to install a compiled
cryptography package beside the Bluetooth one. It is checked against the
FIPS 197 and SP 800-38A vectors and, in the tests, against OpenSSL. It makes
no attempt at constant time: its keys never leave this computer and the
strap, and nothing nearby can time it.
"""

from __future__ import annotations

import secrets

DEGREE = 163
POLY = (1 << 163) | 0xC9  # z^163 + z^7 + z^6 + z^3 + 1


def _words(*words: int) -> int:
    return sum(w << (32 * i) for i, w in enumerate(words))


COEFF_B = _words(0x4A3205FD, 0x512F7874, 0x1481EB10, 0xB8C953CA, 0x0A601907, 0x00000002)
BASE_X = _words(0xE8343E36, 0xD4994637, 0xA0991168, 0x86A2D57E, 0xF0EBA162, 0x00000003)
BASE_Y = _words(0x797324F1, 0xB11C5C0C, 0xA2CDD545, 0x71A0094F, 0xD51FBC6C, 0x00000000)
ORDER = _words(0xA4234C33, 0x77E70C12, 0x000292FE, 0x00000000, 0x00000000, 0x00000004)

KEY_BYTES = 24
Point = tuple[int, int]
INFINITY: Point = (0, 0)


def _mul(a: int, b: int) -> int:
    result = 0
    while b:
        if b & 1:
            result ^= a
        b >>= 1
        a <<= 1
        if a >> DEGREE:
            a ^= POLY
    return result


def _inv(x: int) -> int:
    u, v, g, z = x, POLY, 0, 1
    while u != 1:
        shift = u.bit_length() - v.bit_length()
        if shift < 0:
            u, v, g, z = v, u, z, g
            shift = -shift
        u ^= v << shift
        z ^= g << shift
    return z


def _double(p: Point) -> Point:
    x, y = p
    if x == 0:
        return INFINITY
    lam = _mul(_inv(x), y) ^ x
    x3 = _mul(lam, lam) ^ lam ^ 1  # curve coefficient a = 1
    y3 = _mul(x, x) ^ _mul(lam ^ 1, x3)
    return x3, y3


def _add(p: Point, q: Point) -> Point:
    if q == INFINITY:
        return p
    if p == INFINITY:
        return q
    (x1, y1), (x2, y2) = p, q
    if x1 == x2:
        return _double(p) if y1 == y2 else INFINITY
    lam = _mul(_inv(x1 ^ x2), y1 ^ y2)
    x3 = _mul(lam, lam) ^ lam ^ x1 ^ x2 ^ 1
    y3 = _mul(lam, x1 ^ x3) ^ x3 ^ y1
    return x3, y3


def scalar_mult(k: int, p: Point) -> Point:
    result = INFINITY
    for bit in bin(k)[2:]:
        result = _double(result)
        if bit == "1":
            result = _add(result, p)
    return result


def on_curve(p: Point) -> bool:
    x, y = p
    if p == INFINITY:
        return False
    x2 = _mul(x, x)
    # y^2 + xy = x^3 + x^2 + b
    return _mul(y, y) ^ _mul(x, y) == _mul(x2, x) ^ x2 ^ COEFF_B


def encode_point(p: Point) -> bytes:
    return p[0].to_bytes(KEY_BYTES, "little") + p[1].to_bytes(KEY_BYTES, "little")


def decode_point(data: bytes) -> Point:
    if len(data) != 2 * KEY_BYTES:
        raise ValueError(f"public key must be {2 * KEY_BYTES} bytes, got {len(data)}")
    return int.from_bytes(data[:KEY_BYTES], "little"), int.from_bytes(data[KEY_BYTES:], "little")


def generate_private_key() -> int:
    # tiny-ECDH clears bit 162 and above and rejects keys below 2^81; keep the
    # same range so the device sees what it would from Zepp or Gadgetbridge.
    return secrets.randbits(DEGREE - 1) | (1 << (DEGREE - 2))


def public_key(private: int) -> bytes:
    return encode_point(scalar_mult(private, (BASE_X, BASE_Y)))


def shared_secret(private: int, remote_public: bytes) -> bytes:
    remote = decode_point(remote_public)
    if not on_curve(remote):
        raise ValueError("the strap's public key is not on the B-163 curve")
    # x = 0 is the curve's one point of order two: a "key" that makes the
    # shared secret zero or itself, whatever the private key is.
    shared = scalar_mult(private, remote)
    if remote[0] == 0 or shared == INFINITY:
        raise ValueError("the strap's public key is a degenerate point")
    return encode_point(shared)


# ---- AES-128 (FIPS 197) --------------------------------------------------------


def _sbox() -> tuple[bytes, bytes]:
    """The S-box and its inverse: each byte's inverse in GF(2^8), then the
    affine map, generated by stepping through the field with the generator 3."""
    box = [0] * 256
    p = q = 1
    while True:
        p ^= ((p << 1) & 0xFF) ^ (0x1B if p & 0x80 else 0)  # p times 3
        q ^= q << 1  # q divided by 3
        q ^= q << 2
        q ^= q << 4
        q &= 0xFF
        if q & 0x80:
            q ^= 0x09
        rot = q | (q << 8)
        box[p] = (q ^ (rot >> 7) ^ (rot >> 6) ^ (rot >> 5) ^ (rot >> 4) ^ 0x63) & 0xFF
        if p == 1:
            break
    box[0] = 0x63
    inverse = [0] * 256
    for value, substituted in enumerate(box):
        inverse[substituted] = value
    return bytes(box), bytes(inverse)


_SBOX, _INV_SBOX = _sbox()
BLOCK = 16


def _xtime(a: int) -> int:
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else a << 1


def _times(a: int, b: int) -> int:
    """a times b in GF(2^8), for the small constants of MixColumns."""
    result = 0
    while b:
        if b & 1:
            result ^= a
        a = _xtime(a)
        b >>= 1
    return result


_MUL = {n: bytes(_times(a, n) for a in range(256)) for n in (2, 3, 9, 11, 13, 14)}
# The state is 16 bytes, column by column. ShiftRows moves byte i to here.
_SHIFT = tuple((i + 4 * (i % 4)) % 16 for i in range(16))
_UNSHIFT = tuple(_SHIFT.index(i) for i in range(16))


def _round_keys(key: bytes) -> list[bytes]:
    if len(key) != BLOCK:
        raise ValueError(f"AES-128 keys are 16 bytes, got {len(key)}")
    words = [key[i : i + 4] for i in range(0, 16, 4)]
    rcon = 1
    for i in range(4, 44):
        word = words[i - 1]
        if i % 4 == 0:
            word = bytes(_SBOX[b] for b in word[1:] + word[:1])
            word = bytes([word[0] ^ rcon]) + word[1:]
            rcon = _xtime(rcon)
        words.append(bytes(a ^ b for a, b in zip(words[i - 4], word, strict=True)))
    return [b"".join(words[i : i + 4]) for i in range(0, 44, 4)]


def _encrypt_block(block: bytes, keys: list[bytes]) -> bytes:
    m2, m3 = _MUL[2], _MUL[3]
    state = bytes(a ^ b for a, b in zip(block, keys[0], strict=True))
    for round_ in range(1, 11):
        state = bytes(_SBOX[state[i]] for i in _SHIFT)
        if round_ < 10:
            mixed = bytearray(16)
            for c in range(0, 16, 4):
                a, b, cc, d = state[c : c + 4]
                mixed[c] = m2[a] ^ m3[b] ^ cc ^ d
                mixed[c + 1] = a ^ m2[b] ^ m3[cc] ^ d
                mixed[c + 2] = a ^ b ^ m2[cc] ^ m3[d]
                mixed[c + 3] = m3[a] ^ b ^ cc ^ m2[d]
            state = bytes(mixed)
        state = bytes(a ^ b for a, b in zip(state, keys[round_], strict=True))
    return state


def _decrypt_block(block: bytes, keys: list[bytes]) -> bytes:
    m9, m11, m13, m14 = _MUL[9], _MUL[11], _MUL[13], _MUL[14]
    state = bytes(a ^ b for a, b in zip(block, keys[10], strict=True))
    for round_ in range(9, -1, -1):
        state = bytes(_INV_SBOX[state[i]] for i in _UNSHIFT)
        state = bytes(a ^ b for a, b in zip(state, keys[round_], strict=True))
        if round_ > 0:
            mixed = bytearray(16)
            for c in range(0, 16, 4):
                a, b, cc, d = state[c : c + 4]
                mixed[c] = m14[a] ^ m11[b] ^ m13[cc] ^ m9[d]
                mixed[c + 1] = m9[a] ^ m14[b] ^ m11[cc] ^ m13[d]
                mixed[c + 2] = m13[a] ^ m9[b] ^ m14[cc] ^ m11[d]
                mixed[c + 3] = m11[a] ^ m13[b] ^ m9[cc] ^ m14[d]
            state = bytes(mixed)
    return state


def _blocks(data: bytes) -> list[bytes]:
    if len(data) % BLOCK:
        raise ValueError(f"AES works on whole 16-byte blocks, got {len(data)} bytes")
    return [data[i : i + BLOCK] for i in range(0, len(data), BLOCK)]


def aes_ecb_encrypt(data: bytes, key: bytes) -> bytes:
    keys = _round_keys(key)
    return b"".join(_encrypt_block(block, keys) for block in _blocks(data))


def aes_ecb_decrypt(data: bytes, key: bytes) -> bytes:
    keys = _round_keys(key)
    return b"".join(_decrypt_block(block, keys) for block in _blocks(data))


def aes_cbc_encrypt(data: bytes, key: bytes, iv: bytes) -> bytes:
    """CBC with PKCS#7 padding, as the Zepp sign-in form is sent."""
    if len(iv) != BLOCK:
        raise ValueError(f"the IV is 16 bytes, got {len(iv)}")
    pad = BLOCK - len(data) % BLOCK
    keys = _round_keys(key)
    out, previous = [], iv
    for block in _blocks(data + bytes([pad]) * pad):
        previous = _encrypt_block(bytes(a ^ b for a, b in zip(block, previous, strict=True)), keys)
        out.append(previous)
    return b"".join(out)
